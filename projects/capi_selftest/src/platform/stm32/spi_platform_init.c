/***************************************************************************//**
 * @file spi_platform_init.c
 * @brief STM32 SPI5 platform setup for single-board SPI loopback tests.
 *
 * CubeMX only generates MSP code for SPI1 (the initiator). This file brings up
 * SPI5 (clock, GPIO, NVIC) so the CAPI driver can initialise it as an SPI
 * target (slave). The SPI5 IRQ handler dispatches through the CAPI isr; the
 * test must call spi_platform_set_target_handle() after capi_spi_init() so the
 * vector can reach the correct controller handle.
 *
 * SPI5 is used (rather than SPI3) because its SCK/MISO/MOSI (PF7/PF8/PF9) are
 * all on the populated Zio connector CN9, so the test wires with plain jumpers
 * and no soldering -- SPI3's SCK (PC10) is only on the (unpopulated) morpho
 * header. Role/mode (SPI_MODE_SLAVE with software NSS) are selected by the CAPI
 * driver from config->is_target; the slave is permanently selected in software,
 * so no NSS pin is configured here. This file only wires the peripheral.
 *
 * Wiring (Nucleo-F767ZI, RX-direction loopback):
 *   PA5  (SPI1 SCK,  D13)       -> PF7 (SPI5 SCK,  CN9 pin 24)
 *   PA7  (SPI1 MOSI, D11)       -> PF9 (SPI5 MOSI, CN9 pin 26)
 *   PF8  (SPI5 MISO, CN9 pin 22) left unconnected (slave only receives)
 * The existing PA7 <-> PA6 (D11 <-> D12) MOSI/MISO strap used by the other SPI
 * tests stays; PA7 therefore fans out to both PA6 and PF9 -- join them on a
 * breadboard row or a Y-splitter (still solderless). No NSS wire is needed.
 *
 * Copyright (c) 2026 Analog Devices, Inc.
 * SPDX-License-Identifier: BSD-3-Clause
 *******************************************************************************/

#include <stddef.h>
#include "parameters.h"

#ifdef SPI_TARGET_OPS

#include "stm32_hal.h"
#include "capi_spi.h"

/*
 * HAL handle for the target SPI5. Not generated by CubeMX (which maps only
 * SPI1), so it lives here and is referenced by SPI_TARGET_EXTRA_INIT in
 * parameters.h. The CAPI driver aliases this handle and runs HAL_SPI_Init()
 * lazily on the first armed transfer.
 */
SPI_HandleTypeDef hspi5;

static struct capi_spi_controller_handle *spi5_handle;

int spi_platform_init(void)
{
	GPIO_InitTypeDef gpio_init = { 0 };

	__HAL_RCC_GPIOF_CLK_ENABLE();
	__HAL_RCC_SPI5_CLK_ENABLE();

	/*
	 * SCK/MISO/MOSI on PF7/PF8/PF9, SPI5 alternate function (AF5). MISO
	 * (PF8) is configured for completeness but stays off the bus (the slave
	 * only receives in this test). No NSS pin: software NSS keeps the slave
	 * selected (see the driver's config_peripheral()).
	 */
	gpio_init.Pin = GPIO_PIN_7 | GPIO_PIN_8 | GPIO_PIN_9;
	gpio_init.Mode = GPIO_MODE_AF_PP;
	gpio_init.Pull = GPIO_NOPULL;
	gpio_init.Speed = GPIO_SPEED_FREQ_VERY_HIGH;
	gpio_init.Alternate = GPIO_AF5_SPI5;
	HAL_GPIO_Init(GPIOF, &gpio_init);

	HAL_NVIC_SetPriority(SPI5_IRQn, 1, 0);
	HAL_NVIC_EnableIRQ(SPI5_IRQn);

	hspi5.Instance = SPI5;
	spi5_handle = NULL;

	return 0;
}

void spi_platform_deinit(void)
{
	HAL_NVIC_DisableIRQ(SPI5_IRQn);
	HAL_GPIO_DeInit(GPIOF, GPIO_PIN_7 | GPIO_PIN_8 | GPIO_PIN_9);
	spi5_handle = NULL;
}

void spi_platform_set_target_handle(struct capi_spi_controller_handle *handle)
{
	spi5_handle = handle;
}

void SPI5_IRQHandler(void)
{
	if (spi5_handle)
		capi_spi_isr(spi5_handle);
}

#endif /* SPI_TARGET_OPS */
